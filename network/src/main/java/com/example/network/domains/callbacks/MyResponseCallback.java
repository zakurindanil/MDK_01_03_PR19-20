package com.example.network.domains.callbacks;

/**
 * Интерфейс обратного вызова для обработки результатов асинхронной компиляции.
 * Реализуется классами, которым необходимо получать уведомления о завершении
 * операции компиляции с результатом или ошибкой.
 */
public interface MyResponseCallback {

    // Вызывается при успешном завершении компиляции.
    void onCompile(String result);

    // Вызывается при возникновении ошибки в процессе компиляции.
    void onError(String error);
}
